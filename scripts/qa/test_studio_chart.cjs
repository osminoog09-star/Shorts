const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const html=fs.readFileSync(path.resolve(__dirname,"../../site/studio/index.html"),"utf8");
const code=html.slice(html.indexOf("function chartSeries("),html.indexOf("function videos(){"));
const context={Intl,Date,Map,Number,CH:[],dshort:s=>s,num:n=>String(n)};
vm.createContext(context);vm.runInContext(code,context);
const rows=[{day:"2026-10-01",views:500},{day:"2026-10-31",views:0},{day:"2026-11-01",views:742}];
const series=context.chartSeries(rows,"2026-11-04");
assert.equal(series.length,28);
assert.equal(series[0].x,"2026-10-08");
assert.equal(series.at(-1).x,"2026-11-04");
assert.equal(series.find(p=>p.x==="2026-10-31").y,0);
assert.equal(series.find(p=>p.x==="2026-11-01").y,742);
assert.equal(series.find(p=>p.x==="2026-11-02").y,null);
const markup=context.chart(series);
assert.match(markup,/2026-11-04/);
assert.match(markup,/серые дни/);
assert.match(markup,/rect/);
assert.equal(series.filter(p=>p.y!==null).length,2);
const boundary=context.chartSeries([{day:"2026-12-31",views:1}],"2027-01-02");
assert.equal(boundary.at(-1).x,"2027-01-02");
assert.equal(boundary.find(p=>p.x==="2026-12-31").y,1);
const gaps=context.chart([{x:"2026-11-01",y:1},{x:"2026-11-02",y:null},{x:"2026-11-03",y:2}]);
assert.match(gaps,/d="M0.0,[^"]* M640.0,/,"missing day must break the line");
assert.match(html,/данных пока нет/);
console.log("Calendar chart regression PASS");
